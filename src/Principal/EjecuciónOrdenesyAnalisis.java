    private void cargarPacientes() {
        comboBoxPaciente.removeAllItems();

        for (Paciente p : GestionPacientes.listaPacientes) {
            comboBoxPaciente.addItem(p.getNombres() + " " + p.getApellidos());
        }
    }

    private void actualizarTabla() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        for (Orden ord : EjecuciónOrdenesyAnalisis.listaOrdenes) {
            model.addRow(new Object[]{
                ord.getNombre(),
                ord.getDescripcion(),
                ord.getPrecio(),
                ord.getEstado(),
                ord.getResultado(),
                ord.getPaciente().getNombres() + " " + ord.getPaciente().getApellidos()
            });
        }
    }

    private void limpiarCampos() {
        ComboBoxTipo.setSelectedIndex(0);
        IngresarDescripción.setText("");
        if (comboBoxPaciente.getItemCount() > 0) {
            comboBoxPaciente.setSelectedIndex(0);
        }
    }

