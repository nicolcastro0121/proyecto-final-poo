    private void IngresarDescripciónActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_IngresarDescripciónActionPerformed
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una orden.");
            return;
        }

        EjecuciónOrdenesyAnalisis.listaOrdenes.remove(fila);
        actualizarTabla();
    }//GEN-LAST:event_IngresarDescripciónActionPerformed

    private void ModficarbtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ModficarbtActionPerformed
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una orden.");
            return;
        }

        Orden ord = EjecuciónOrdenesyAnalisis.listaOrdenes.get(fila);
        indiceModificar = fila;

        ComboBoxTipo.setSelectedItem(ord.getNombre());
        IngresarDescripción.setText(ord.getDescripcion());

        for (int i = 0; i < GestionPacientes.listaPacientes.size(); i++) {
            Paciente p = GestionPacientes.listaPacientes.get(i);
            if (p == ord.getPaciente()) {
                comboBoxPaciente.setSelectedIndex(i);
                break;
            }
        }
    }//GEN-LAST:event_ModficarbtActionPerformed

