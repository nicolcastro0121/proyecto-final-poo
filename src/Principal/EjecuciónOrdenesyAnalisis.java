    private void AgregarbtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AgregarbtActionPerformed
        String nombre = ComboBoxTipo.getSelectedItem().toString();
        String descripcion = IngresarDescripción.getText();

        int indexPac = comboBoxPaciente.getSelectedIndex();
        if (indexPac == -1) {
            JOptionPane.showMessageDialog(this, "No hay pacientes para seleccionar.");
            return;
        }

        Paciente pac = GestionPacientes.listaPacientes.get(indexPac);
        double precio = 0.0;

        Orden nueva = new Orden(nombre, descripcion, precio, pac);
        EjecuciónOrdenesyAnalisis.listaOrdenes.add(nueva);

        actualizarTabla();
        limpiarCampos();
    }//GEN-LAST:event_AgregarbtActionPerformed

    private void GuardarCambiosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GuardarCambiosActionPerformed
        if (indiceModificar == null) {
            JOptionPane.showMessageDialog(this, "No estás modificando ninguna orden.");
            return;
        }

        Orden ord = EjecuciónOrdenesyAnalisis.listaOrdenes.get(indiceModificar);

        ord.setNombre(ComboBoxTipo.getSelectedItem().toString());
        ord.setDescripcion(IngresarDescripción.getText());

        Paciente pac = GestionPacientes.listaPacientes.get(comboBoxPaciente.getSelectedIndex());
        ord.setPaciente(pac);

        indiceModificar = null;
        actualizarTabla();
        limpiarCampos();
    }//GEN-LAST:event_GuardarCambiosActionPerformed

