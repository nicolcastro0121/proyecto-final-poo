    private void ModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ModificarActionPerformed
        int fila = jTable1.getSelectedRow();
        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un paciente para modificar.");
            return;
        }

        indiceSeleccionado = fila;

        Paciente p = sistema.getGestionPacientes().getPaciente(fila);

        Dni.setText(p.getDni());
        Nombre.setText(p.getNombres());
        Apellido.setText(p.getApellidos());
        Fecha_Nacimiento.setText(p.getFechaNacimiento());
        Sexo.setText(p.getSexo());
        Telefono.setText(p.getTelefono());
        Direccion.setText(p.getDireccion());
        Contacto_Emergencia.setText(p.getContactoEmergencia());

    }//GEN-LAST:event_ModificarActionPerformed

    private void EliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EliminarActionPerformed
        String dniEliminar = DNIextfieldeliminar.getText().trim();

        if (dniEliminar.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el DNI del paciente a eliminar.");
            return;
        }

        boolean eliminado = sistema.getGestionPacientes().eliminar(dniEliminar);

        if (eliminado) {
            javax.swing.JOptionPane.showMessageDialog(this, "Paciente eliminado correctamente.");
            actualizarTabla();
            DNIextfieldeliminar.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontró un paciente con ese DNI.");
        }
    }//GEN-LAST:event_EliminarActionPerformed

