    private void AceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AceptarActionPerformed
        String dni = Dni.getText().trim();
        String nombre = Nombre.getText().trim();
        String apellido = Apellido.getText().trim();
        String fecha = Fecha_Nacimiento.getText().trim();
        String sexo = Sexo.getText().trim();
        String telefono = Telefono.getText().trim();
        String direccion = Direccion.getText().trim();
        String contacto = Contacto_Emergencia.getText().trim();
        if (dni.isEmpty() || nombre.isEmpty() || apellido.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete al menos DNI, Nombre y Apellido.");
            return;
        }
        Paciente nuevo = new Paciente(
                dni,
                nombre,
                apellido,
                fecha,
                sexo,
                telefono,
                direccion,
                contacto
        );

        boolean agregado = sistema.getGestionPacientes().agregar(nuevo);

        if (agregado) {
            javax.swing.JOptionPane.showMessageDialog(this, "Paciente agregado correctamente.");
            actualizarTabla();
            limpiarCampos();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo agregar el paciente (lista llena).");
        }

    }//GEN-LAST:event_AceptarActionPerformed

    private void GuardarCambiosbtActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GuardarCambiosbtActionPerformed
        if (indiceSeleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "No hay paciente seleccionado para modificar.");
            return;
        }

        Paciente p = sistema.getGestionPacientes().getPaciente(indiceSeleccionado);

        p.setDni(Dni.getText());
        p.setNombres(Nombre.getText());
        p.setApellidos(Apellido.getText());
        p.setFechaNacimiento(Fecha_Nacimiento.getText());
        p.setSexo(Sexo.getText());
        p.setTelefono(Telefono.getText());
        p.setDireccion(Direccion.getText());
        p.setContactoEmergencia(Contacto_Emergencia.getText());

        actualizarTabla();
        limpiarCampos();
        indiceSeleccionado = -1;

        javax.swing.JOptionPane.showMessageDialog(this, "Paciente modificado correctamente.");
    }//GEN-LAST:event_GuardarCambiosbtActionPerformed

